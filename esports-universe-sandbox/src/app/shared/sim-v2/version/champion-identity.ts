export function buildChampionIdentity(championId: string): ChampionIdentity {
  const kit = CHAMPION_KITS[championId];
  const base = kit ? fromKit(kit) : { ...BASE };
  const signature = SIGNATURE[championId];
  return signature ? overlay(base, signature) : base;
}

export function identityPhasePower(identity: ChampionIdentity, timeSec: number): number {
  const minutes = timeSec / 60;
  const point =
    minutes < 14
      ? identity.early + ((identity.mid - identity.early) * minutes) / 14
      : minutes < 28
        ? identity.mid + ((identity.late - identity.mid) * (minutes - 14)) / 14
        : identity.late;
  return point / 60;
}
