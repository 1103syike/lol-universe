function fromKit(kit: ChampionKit): ChampionIdentity {
  const classBias: Partial<ChampionIdentity> =
    kit.combatClass === 'assassin'
      ? { skirmish: 12, closeout: 10, gankThreat: 18, teamfight: -8, peel: -15 }
      : kit.combatClass === 'marksman'
        ? { laning: 8, teamfight: 6, closeout: 8, waveClear: 10, engage: -15, peel: -10 }
        : kit.combatClass === 'mage'
          ? { teamfight: 8, waveClear: 12, objective: 4 }
          : kit.combatClass === 'tank'
            ? { engage: 20, peel: 18, teamfight: 12, closeout: -12, laning: -5 }
            : kit.combatClass === 'support'
              ? { peel: 16, engage: 8, teamfight: 10, closeout: -10, laning: -8 }
              : kit.combatClass === 'fighter'
                ? { skirmish: 10, splitPush: 10, closeout: 6, laning: 6 }
                : {};

  return clampIdentity({
    laning: kit.style.laning + (classBias.laning ?? 0) - 10,
    skirmish: (kit.style.laning + kit.style.engage) / 2 + (classBias.skirmish ?? 0) - 5,
    teamfight: kit.style.teamfight + (classBias.teamfight ?? 0) - 10,
    closeout: (kit.scaling.late + kit.style.teamfight) / 2 + (classBias.closeout ?? 0) - 15,
    splitPush: kit.style.splitPush + (classBias.splitPush ?? 0) - 10,
    gankThreat:
      kit.positions.includes('JUNGLE') || kit.combatClass === 'assassin'
        ? 60 + (classBias.gankThreat ?? 0)
        : 35 + (classBias.gankThreat ?? 0),
    objective: 48 + (kit.style.teamfight + kit.style.engage) / 20 + (classBias.objective ?? 0),
    waveClear:
      kit.combatClass === 'mage' || kit.combatClass === 'marksman'
        ? 62 + (classBias.waveClear ?? 0)
        : 45 + (classBias.waveClear ?? 0),
    mobility: kit.combatClass === 'assassin' ? 70 : kit.style.engage > 70 ? 55 : 42,
    engage: kit.style.engage + (classBias.engage ?? 0) - 10,
    peel: kit.style.engage < 40 ? 55 + (classBias.peel ?? 0) : 35 + (classBias.peel ?? 0),
    early: kit.scaling.early,
    mid: kit.scaling.mid,
    late: kit.scaling.late,
  });
}

function clampIdentity(raw: ChampionIdentity): ChampionIdentity {
  const clamp = (value: number) => Math.max(5, Math.min(98, Math.round(value)));
  return {
    laning: clamp(raw.laning),
    skirmish: clamp(raw.skirmish),
    teamfight: clamp(raw.teamfight),
    closeout: clamp(raw.closeout),
    splitPush: clamp(raw.splitPush),
    gankThreat: clamp(raw.gankThreat),
    objective: clamp(raw.objective),
    waveClear: clamp(raw.waveClear),
    mobility: clamp(raw.mobility),
    engage: clamp(raw.engage),
    peel: clamp(raw.peel),
    early: clamp(raw.early),
    mid: clamp(raw.mid),
    late: clamp(raw.late),
  };
}

function overlay(
  base: ChampionIdentity,
  patch: Partial<ChampionIdentity>,
): ChampionIdentity {
  return clampIdentity({ ...base, ...patch });
}

